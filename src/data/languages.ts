export function getLanguageOption(code: string): LanguageOption {
  if (code === 'auto') {
    return { code: 'auto', name: 'Otomatik Algıla', nativeName: 'Auto Detect', flag: '🌐' };
  }
  const found = ALL_LANGUAGES.find((l) => l.code.toLowerCase() === code.toLowerCase());
  return found || { code, name: code.toUpperCase(), nativeName: code, flag: '🌐' };
}

export function getLanguageName(code: string): string {
  if (code === 'auto') return 'Otomatik Algıla';
  const opt = getLanguageOption(code);
  return opt.name;
}

export function getLanguageNativeName(code: string): string {
  if (code === 'auto') return 'Auto Detect';
  const opt = getLanguageOption(code);
  return opt.nativeName || opt.name;
}

export function getLanguageFlag(code: string): string {
  if (code === 'auto') return '🌐';
  const opt = getLanguageOption(code);
  return opt.flag;
}

export function searchLanguages(query: string, regionFilter: string = 'all'): LanguageOption[] {
  const q = (query || '').trim().toLowerCase();
  return ALL_LANGUAGES.filter((lang) => {
    if (regionFilter !== 'all' && lang.region !== regionFilter) return false;
    if (!q) return true;
    return (
      lang.name.toLowerCase().includes(q) ||
      (lang.nativeName && lang.nativeName.toLowerCase().includes(q)) ||
      lang.code.toLowerCase().includes(q)
    );
  });
}

