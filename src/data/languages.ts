// Merge all translated dictionaries
export const ALL_UI_TRANSLATIONS: Record<string, Record<string, string>> = {
  ...UI_TRANSLATIONS,
  ...EXTENDED_TRANSLATIONS,
  ...EXTENDED_TRANSLATIONS_2,
};

// Dynamic client translation cache for live AI / on-the-fly translated strings in any language
const dynamicUiCache: Record<string, Record<string, string>> = {};

export function t(key: string, langCode: string = 'tr', fallback?: string): string {
  const norm = (langCode || 'tr').toLowerCase();
  const primaryCode = norm.split('-')[0];

  // 1. Direct match in combined dictionary
  if (ALL_UI_TRANSLATIONS[norm] && ALL_UI_TRANSLATIONS[norm][key]) {
    return ALL_UI_TRANSLATIONS[norm][key];
  }
  // 2. Primary code match (e.g. 'zh' for 'zh-CN', 'en' for 'en-US')
  if (ALL_UI_TRANSLATIONS[primaryCode] && ALL_UI_TRANSLATIONS[primaryCode][key]) {
    return ALL_UI_TRANSLATIONS[primaryCode][key];
  }
  // 3. Dynamic cache lookup
  if (dynamicUiCache[norm] && dynamicUiCache[norm][key]) {
    return dynamicUiCache[norm][key];
  }
  // 4. Fallback to English
  if (ALL_UI_TRANSLATIONS['en'] && ALL_UI_TRANSLATIONS['en'][key]) {
    return ALL_UI_TRANSLATIONS['en'][key];
  }
  // 5. Fallback to Turkish
  if (ALL_UI_TRANSLATIONS['tr'] && ALL_UI_TRANSLATIONS['tr'][key]) {
    return ALL_UI_TRANSLATIONS['tr'][key];
  }
  return fallback || key;
}
